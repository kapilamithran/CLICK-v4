**Definition**
Type casting means changing a value from one data type to another. For example:
```c
int number = 10;
float result = (float) number;
```
Here, the int value 10 is converted into a float.

**Look at the small part**
`(float) number` — float → the type we want. number → the value we want to convert. ( ) → tells C to perform the conversion.

**Why do we need it?**
Sometimes the type of a value can affect the result. Look at: `int result = 5 / 2;` → Output: `2`. But mathematically, 5 ÷ 2 = 2.5. The problem is that both numbers are integers, so C performs integer division.

That''s where type casting helps! `float result = (float)5 / 2;` → Now: `2.5`

**Easy memory line**
Type casting = "Change this value into another type."//.//Think of It Like Changing a Container
Imagine you have 5 apples. You can keep them in a box meant for whole items: WHOLE NUMBER → 5. Now suppose you need to use that value where decimal numbers are expected: DECIMAL → 5.0. The number is still 5 — we''re simply using it in a different data type.

**In C**
```c
int number = 5;
float result = number;
```
C can convert the value when it is assigned to result. number(5) → float result(5.0)

**But conversion can also go the other way**
Suppose we have:
```c
float price = 9.8;
int amount = (int)price;
```
We''re asking C to use price as an int. 9.8 → int → 9. The .8 is not kept because an int stores whole numbers.

**So what''s the big idea?**
Type casting/conversion is simply using a value as a different data type.

**Remember**
int → whole number. float → decimal number. When a value needs to work with another type, C can convert it — either automatically or because we tell it to.//.//Two Ways C Can Convert
**1. Implicit Conversion**
Sometimes we don''t have to write anything. C automatically converts the value when the receiving variable needs a different type.
```c
int number = 10;
float result = number;
```
number → an int containing 10. result → a float. Because result needs a float, C automatically converts the value: int 10 → C converts it automatically → float 10.0

**Important**
The original number is still an int. C only converts the value for the new float variable.

**Easy memory line**
The receiving type tells C what type is needed.

**2. Explicit Casting**
Sometimes we want to tell C exactly what type to use.
```c
float number = 9.8;
int result = (int)number;
```
Here we write `(int)number`: (int) → the type we want. number → the value we want to convert. 9.8 → (int) → 9. The decimal part is discarded when converting to int.

**Easy memory trick**
Implicit → C decides. Explicit → You decide.//.//Let''s See Why It Matters!
**Example: Division**
