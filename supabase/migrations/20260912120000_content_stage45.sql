```c
switch(value) {
       case 1:
              // action
              break;
       case 2:
              // action
              break;
}
```

**Example**
```c
int day = 2;

switch(day) {
       case 1:  printf("Monday"); break;
       case 2:  printf("Tuesday"); break;
}
```

**Remember**
