**Definition**
The ternary operator is a compact decision-making feature in C. It is used when a program needs to choose between two possible values based on a condition. It works like a simple YES/NO decision. First, C checks the condition. If the condition is TRUE, the first choice is selected. If it is FALSE, the second choice is selected.

**Simple Idea**
Condition → Check → Choose ONE result

**Analogy**
Imagine a security gate asking: "Is your age 18 or above?" YES → Allow entry. NO → Deny entry. The ternary operator performs this kind of quick two-way selection.

**Basic Pattern**
`condition ? TRUE choice : FALSE choice`

**Example**
```c
int age = 20;
printf("%s", (age >= 18) ? "Adult" : "Minor");
```
20 ≥ 18 → TRUE → Adult

**Remember**
Ternary = one condition + two choices + one result//.//From Basic to Professional
A ternary expression has three important parts:
1. Condition — The question C needs to check.
2. TRUE value — The value selected when the condition is TRUE.
3. FALSE value — The value selected when the condition is FALSE.

The symbols make the decision easy to read: `?` introduces the TRUE choice. `:` introduces the FALSE choice.

**Think Like This**
"If this is true, take this; otherwise, take that."

This makes ternary useful when the decision is short and produces a single result.

**Example**
```c
int marks = 75;
char *result = (marks >= 50) ? "Pass" : "Fail";
