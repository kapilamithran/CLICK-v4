A switch works in three simple steps:
1. Take a value → day
2. Compare it → with each case
3. Run the matching case → then break

**Important Keywords**
switch → starts the selection. case → represents one possible value. break → stops the switch after a match. default → runs when no case matches.

**Example**
```c
int choice = 2;

switch(choice) {
        case 1: printf("Start"); break;
        case 2: printf("Stop"); break;
        default: printf("Invalid");
}
```

**Professional Tip**
Use switch-case when the choices are clear, fixed, and based on one value.

